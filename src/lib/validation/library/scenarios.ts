/** Step ids are made stable and scenario-local (step-1, step-2, …) so a definition's hash never depends on library order. */
function finalize(sc: ScenarioInput): ScenarioInput {
  const map = new Map<string, string>();
  sc.steps.forEach((st, i) => map.set(st.id, st.id.startsWith("tmp-") ? `step-${i + 1}` : st.id));
  return {
    ...sc,
    steps: sc.steps.map((st) => ({
      ...st,
      id: map.get(st.id) ?? st.id,
      ...(st.ref ? { ref: map.get(st.ref) ?? st.ref } : {}),
    })),
  };
}

export const SCENARIOS: Scenario[] = RAW.map(finalize).map((sc) => scenarioSchema.parse(sc));

export const SCENARIO_BY_KEY = new Map(SCENARIOS.map((s) => [s.key, s]));
